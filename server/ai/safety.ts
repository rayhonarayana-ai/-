export function composeSystemInstruction(options: {
  basePersona?: string;
  persona?: string;
  personaPrompt?: string;
  language?: string;
}): string {
  const parts: string[] = [];

  // Base persona & safety
  parts.push(options.basePersona || ZAKI_BASE_PERSONA);
  parts.push(BASE_CHILD_SAFETY_RULES);

  // Persona instructions
  if (options.personaPrompt && options.personaPrompt.trim()) {
    // Sanitize user persona prompt
    const sanitizedPrompt = sanitizeText(options.personaPrompt, 300);
    parts.push(`\n[شخصية المعلم المحددة]:\n${sanitizedPrompt}`);
  } else if (options.persona === "wise") {
    parts.push("\n[شخصية المعلم]: أنت «الأستاذ زكي الحكيم» 🎓. تحب الشرح الرفيع والمنظم، القائم على الأسئلة المنطقية والتفكير الهادئ المتدرج.");
  } else if (options.persona === "explorer") {
    parts.push("\n[شخصية المعلم]: أنت «الأستاذ زكي المستكشف» 🚀. تتحدث بشغف وحماس عاليين، وتستخدم تشبيهات المغامرات الفضائية والاستكشاف في مجرات التكنولوجيا.");
  } else if (options.persona === "artist") {
    parts.push("\n[شخصية المعلم]: أنت «الأستاذ زكي المبدع» 🎨. تركز على الخيال، الألوان، القصص التفاعلية، وتصميم الأفكار الإبداعية.");
  } else if (options.persona === "digital") {
    parts.push("\n[شخصية المعلم]: أنت «الأستاذ زكي الرقمي» 🤖. معلم الخوارزميات والبرمجة، تحب لغة الشفرات والمستقبل وتفكير الحاسوب والروبوتات.");
  }

  // Language instructions
  const lang = options.language || "ar_fusha";
  if (lang === "darija") {
    parts.push("\n[تعليمات اللغة الإلزامية]: يتوجب عليك التحدث حتماً بالدارجة المغربية السلسة، المحببة والسهلة للأطفال (مثل: مرحباً بيك أ صاحبي، تبارك الله عليك، واش عارف باللي...).");
  } else if (lang === "fr") {
    parts.push("\n[MANDATORY LANGUAGE INSTRUCTION]: You must respond strictly in simple, warm, child-friendly French suited for kids aged 7-14 (e.g. Salut mon ami ! Bravo, tu es un vrai champion !).");
  } else if (lang === "en") {
    parts.push("\n[MANDATORY LANGUAGE INSTRUCTION]: You must respond strictly in simple, friendly, enthusiastic English suited for kids aged 7-14 (e.g. Welcome my friend! You are doing awesome!).");
  } else if (lang === "amazigh") {
    parts.push("\n[تعليمات اللغة الإلزامية]: يتوجب عليك التحدث بعبارات وتحيات أمازيغية لطيفة ومبسطة للأطفال (مثل: ⴰⵣⵓⵍ Azul - مرحباً) مع شرح ودود باللغة البسيطة.");
  } else {
    parts.push("\n[تعليمات اللغة الإلزامية]: يتوجب عليك التحدث حصراً باللغة العربية الفصحى البسيطة والدافئة والمشجعة للأطفال.");
  }

  return parts.join("\n\n");
}

export function sanitizeText(text: unknown, maxLen = 800): string {
  if (typeof text !== "string") return "";
  // Strip control characters except newline and tab
  const cleaned = text.replace(/[\u0000-\u0008\u000B-\u001F\u007F-\u009F]/g, "").trim();
  return cleaned.slice(0, maxLen);
}
